"""Install, uninstall and repair.

Install is idempotent: running it twice leaves the same files, one copy of
each hook and one CLAUDE.md block. Uninstall removes exactly what install
added and keeps the vault unless asked otherwise.
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

from . import MIN_PYTHON, __version__, util, vault as V

REPO = Path(__file__).resolve().parent.parent
HOOK_MARKER = "jarvan-memory/hook.sh"
BLOCK_BEGIN = "<!-- jarvan-memory:begin -->"
BLOCK_END = "<!-- jarvan-memory:end -->"
MODULES = ("summary", "backup", "sweep")
PLACEHOLDER_RE = re.compile(r"\{\{[A-Z_]+\}\}")

# (event, matcher, hook name, timeout seconds)
HOOKS = [
    ("SessionStart", None, "session-start", 20),
    ("UserPromptSubmit", None, "user-prompt", 10),
    ("PreToolUse", "Write|Bash", "pre-tool", 10),
    ("PostToolUse", "Write|Edit|MultiEdit|NotebookEdit|Bash", "post-tool", 10),
    ("PostToolUseFailure", "Bash", "tool-failure", 10),
    ("Stop", None, "stop", 10),
    ("SessionEnd", None, "session-end", 20),
]


# ----------------------------------------------------------------- python

def probe_python(exe):
    """Run the candidate and ask it who it is. Name lookup is not enough: the
    Windows Store alias `python3` is on PATH, prints an install hint and
    exits 0. Only an interpreter that actually runs code answers here."""
    code = ("import sys,sqlite3,json;print(json.dumps({'exe':sys.executable,"
            "'ver':list(sys.version_info[:2])}))")
    try:
        r = subprocess.run([exe, "-c", code], capture_output=True, text=True, timeout=20,
                           encoding="utf-8", errors="replace")
    except (OSError, subprocess.SubprocessError):
        return None
    if r.returncode != 0:
        return None
    try:
        info = json.loads(r.stdout.strip().splitlines()[-1])
    except (ValueError, IndexError):
        return None
    real = info.get("exe") or ""
    if not real or not Path(real).is_file() or "WindowsApps" in real:
        # The Store build lives under WindowsApps and sandboxes file writes
        # under AppData; hooks need the real file system.
        return None
    if tuple(info["ver"]) < MIN_PYTHON:
        return None
    return util.fwd(real)


def find_python(explicit=None):
    cands = [explicit] if explicit else []
    cands += [sys.executable]
    for name in ("python3", "python", "py"):
        p = shutil.which(name)
        if p:
            cands.append(p)
    for c in cands:
        if c:
            real = probe_python(c)
            if real:
                return real
    return None


# ----------------------------------------------------------------- generated files

HOOK_SH = """#!/bin/sh
# jarvan-memory hook shim, generated by the installer. Do not edit; re-run
# the installer or `mem repair-python` instead.
[ -n "$JARVAN_MEMORY_CHILD" ] && exit 0
PY="{{PYTHON}}"
RUN="{{RUN}}"
if [ ! -f "$PY" ]; then
  # Without Python no hook can run. Say so at session start instead of
  # failing silently: a dead memory looks exactly like an empty one.
  if [ "$1" = "session-start" ]; then
    printf '%s\\n' '{"hookSpecificOutput":{"hookEventName":"SessionStart","additionalContext":"[jarvan-memory] The Python interpreter recorded at install ({{PYTHON_JSON}}) no longer exists, so the memory hooks are not running. Fix: install Python 3.9+ and run: <new-python> {{RUN_JSON}} cli repair-python  (or re-run install.py from the jarvan-memory repo). Tell the user."}}'
  fi
  exit 0
fi
PYTHONUTF8=1 PYTHONIOENCODING=utf-8 exec "$PY" -B "$RUN" hook "$1"
"""

MEM_SH = """#!/bin/sh
# jarvan-memory CLI launcher, generated by the installer.
PY="{{PYTHON}}"
if [ ! -f "$PY" ]; then
  echo "mem: the Python interpreter $PY is gone. Install Python 3.9+ and run: <new-python> {{RUN}} cli repair-python" >&2
  exit 1
fi
PYTHONUTF8=1 PYTHONIOENCODING=utf-8 exec "$PY" -B "{{RUN}}" cli "$@"
"""

MEM_CMD = """@echo off
rem jarvan-memory CLI launcher for cmd/PowerShell, generated by the installer.
set PYTHONUTF8=1
"{{PYTHON_WIN}}" -B "{{RUN_WIN}}" cli %*
"""


def _fill(text, values):
    for k, v in values.items():
        text = text.replace("{{" + k + "}}", v)
    return text


def write_runtime(python):
    app = util.app_dir()
    rt = app / "runtime"
    if rt.exists():
        shutil.rmtree(rt)
    (rt / "jarvan_memory").mkdir(parents=True)
    for f in (REPO / "jarvan_memory").glob("*.py"):
        shutil.copy2(f, rt / "jarvan_memory" / f.name)
    shutil.copy2(REPO / "run.py", rt / "run.py")
    write_shims(python)


def write_shims(python):
    app = util.app_dir()
    run = util.fwd(app / "runtime" / "run.py")
    values = {"PYTHON": python, "RUN": run,
              "PYTHON_JSON": python.replace('"', ""), "RUN_JSON": run.replace('"', ""),
              "PYTHON_WIN": python.replace("/", "\\"), "RUN_WIN": run.replace("/", "\\")}
    util.write_text(app / "hook.sh", _fill(HOOK_SH, values))
    util.write_text(app / "bin" / "mem", _fill(MEM_SH, values))
    util.write_text(app / "bin" / "mem.cmd", _fill(MEM_CMD, values).replace("\n", "\r\n"))
    for p in (app / "hook.sh", app / "bin" / "mem"):
        try:
            p.chmod(0o755)
        except OSError:
            pass


def hook_command(event_name):
    return f'bash "{util.fwd(util.app_dir() / "hook.sh")}" {event_name}'


def mem_command():
    return f'"{util.fwd(util.app_dir() / "bin" / "mem")}"'


# ----------------------------------------------------------------- settings.json

def settings_path():
    return util.claude_dir() / "settings.json"


def _is_ours(hook):
    return isinstance(hook, dict) and HOOK_MARKER in str(hook.get("command", ""))


def strip_ours(settings):
    hooks = settings.get("hooks")
    if not isinstance(hooks, dict):
        return settings
    for ev in list(hooks):
        groups = hooks[ev]
        if not isinstance(groups, list):
            continue
        kept = []
        for g in groups:
            if isinstance(g, dict) and isinstance(g.get("hooks"), list):
                inner = [h for h in g["hooks"] if not _is_ours(h)]
                if not inner and any(_is_ours(h) for h in g["hooks"]):
                    continue
                g = dict(g, hooks=inner)
            kept.append(g)
        if kept:
            hooks[ev] = kept
        else:
            del hooks[ev]
    return settings


def merge_settings(settings):
    """Add our hooks; every foreign hook and key is preserved. Idempotent:
    our old entries are removed first, then added once."""
    settings = strip_ours(settings)
    hooks = settings.setdefault("hooks", {})
    for ev, matcher, name, timeout in HOOKS:
        group = {"hooks": [{"type": "command", "command": hook_command(name),
                            "timeout": timeout}]}
        if matcher:
            group = {"matcher": matcher, **group}
        hooks.setdefault(ev, []).append(group)
    return settings


def read_settings():
    p = settings_path()
    if not p.exists():
        return None
    text = p.read_text(encoding="utf-8-sig")
    if not text.strip():
        return {}
    try:
        data = json.loads(text)
    except ValueError as e:
        raise SystemExit(f"{p} is not valid JSON ({e}). Fix it by hand first; the installer "
                         "never overwrites a settings file it cannot read.")
    if not isinstance(data, dict):
        raise SystemExit(f"{p} does not contain a JSON object")
    return data


def write_settings(data, backups):
    p = settings_path()
    if p.exists():
        stem = f"settings.json.jarvan-memory-{time.strftime('%Y%m%d-%H%M%S')}"
        b, n = p.with_name(stem + ".bak"), 1
        while b.exists():  # two installs in one second must not overwrite the original
            n += 1
            b = p.with_name(f"{stem}-{n}.bak")
        shutil.copy2(p, b)
        backups.append(util.fwd(b))
    util.write_text(p, json.dumps(data, indent=2, ensure_ascii=False) + "\n")


# ----------------------------------------------------------------- CLAUDE.md

def claude_md_path():
    return util.claude_dir() / "CLAUDE.md"


def claude_block(cfg):
    contract = util.fwd(Path(cfg["vault"]) / V.CONTRACT)
    mem = cfg["mem_cmd"]
    return (f"{BLOCK_BEGIN}\n"
            "## Memory (jarvan-memory)\n\n"
            "This machine has a persistent memory vault. Its contract is "
            f"`{contract}`: read it before relying on memory or writing to it. "
            f"The memory command is `{mem}` (it stamps all dates; never type one). "
            f"To find something, run `{mem} search \"<question>\"` first.\n"
            f"{BLOCK_END}")


def _read_keep_newlines(p):
    with open(p, encoding="utf-8", newline="") as f:
        return f.read()


BLOCK_RE = re.compile(re.escape(BLOCK_BEGIN) + r".*?" + re.escape(BLOCK_END), re.S)


def install_claude_md(cfg):
    p = claude_md_path()
    block = claude_block(cfg)
    text = _read_keep_newlines(p) if p.exists() else None
    if text is not None and BLOCK_RE.search(text):
        util.write_text(p, BLOCK_RE.sub(lambda m: block, text, count=1))
        return None
    # Remember the separator so uninstall restores the file byte for byte.
    sep = "" if not text else ("\n" if text.endswith("\n") else "\n\n")
    util.write_text(p, (text or "") + sep + block + "\n")
    return {"created": text is None, "sep": sep}


def remove_claude_md(record):
    p = claude_md_path()
    if not p.exists():
        return
    text = _read_keep_newlines(p)
    m = BLOCK_RE.search(text)
    if not m:
        return
    start, end = m.start(), m.end()
    if text[end:end + 1] == "\n":
        end += 1
    sep = (record or {}).get("sep", "")
    if sep and text[start - len(sep):start] == sep:
        start -= len(sep)
    new = text[:start] + text[end:]
    if (record or {}).get("created") and not new.strip():
        p.unlink()
    else:
        util.write_text(p, new)


# ----------------------------------------------------------------- vault

def template_values(cfg, profile):
    return {"VAULT": util.fwd(cfg["vault"]), "MEM": cfg["mem_cmd"],
            "USER_NAME": profile.get("name") or "the user",
            "USER_ABOUT": profile.get("about") or "(not stated yet)",
            "LANGUAGE": cfg.get("language", "English"),
            "INSTALL_DATE": util.today()}


def build_vault(cfg, profile):
    vroot = Path(cfg["vault"])
    created = not vroot.exists()
    vroot.mkdir(parents=True, exist_ok=True)
    for d in V.SKELETON_DIRS:
        (vroot / d).mkdir(exist_ok=True)
    values = template_values(cfg, profile)
    src = REPO / "template" / "vault"
    for f in src.rglob("*"):
        if f.is_dir():
            continue
        dest = vroot / f.relative_to(src)
        if dest.exists():
            continue  # never overwrite the user's notes
        dest.parent.mkdir(parents=True, exist_ok=True)
        if f.suffix in (".md", ".gitignore") or f.name == ".gitignore":
            util.write_text(dest, _fill(f.read_text(encoding="utf-8"), values))
        else:
            shutil.copy2(f, dest)
    return created


def setup_git(vroot):
    if not shutil.which("git"):
        return "git not found; backup module will report this until git is installed"
    if not (Path(vroot) / ".git").exists():
        r = subprocess.run(["git", "init", "-q", str(vroot)], capture_output=True, text=True)
        if r.returncode != 0:
            return "git init failed: " + r.stderr.strip()
    return None


# ----------------------------------------------------------------- install

def default_vault():
    return util.home() / "claude-memory"


def parse_args(argv):
    ap = argparse.ArgumentParser(prog="install.py", description=(
        "Install jarvan-memory for Claude Code. An agent installing this should ask the "
        "user the interview questions in INSTALL.md first and pass the answers as flags."))
    ap.add_argument("--vault", help=f"vault folder (default {default_vault()})")
    ap.add_argument("--name", help="what to call the user")
    ap.add_argument("--about", help="one or two sentences: what the user does / works on")
    ap.add_argument("--language", help="language for the vault's prose, e.g. English, Turkish")
    ap.add_argument("--modules", default=None,
                    help="comma list of optional modules: summary,backup,sweep (or 'none')")
    ap.add_argument("--stemmer", choices=["none", "tr"], help="optional search stemmer plugin")
    ap.add_argument("--python", help="interpreter to use for the hooks (absolute path)")
    ap.add_argument("--no-doctor", action="store_true", help="skip the final self-check")
    return ap.parse_args(argv)


def main(argv):
    a = parse_args(argv)
    old = util.load_config(required=False)
    python = find_python(a.python)
    if not python:
        util.err("No working Python 3.9+ interpreter found (the Windows Store alias does not "
                 "count). See INSTALL.md, 'Python', then re-run.")
        return 1
    vault_path = Path(os.path.expanduser(a.vault)).resolve() if a.vault else \
        Path(old.get("vault") or default_vault())
    mods = old.get("modules", [])
    if a.modules is not None:
        mods = [] if a.modules.strip() in ("", "none") else \
            [m.strip() for m in a.modules.split(",") if m.strip()]
        bad = [m for m in mods if m not in MODULES]
        if bad:
            util.err(f"unknown module(s): {', '.join(bad)}; choose from {', '.join(MODULES)}")
            return 1
    record = old.get("installed", {})
    cfg = dict(old)
    cfg.update({
        "version": __version__,
        "vault": util.fwd(vault_path),
        "python": python,
        "mem_cmd": mem_command(),
        "modules": mods,
        "language": a.language or old.get("language") or "English",
        "stemmer": (a.stemmer if a.stemmer and a.stemmer != "none" else
                    (None if a.stemmer == "none" else old.get("stemmer"))),
        "stop_gate_prompts": old.get("stop_gate_prompts", 10),
        "summary_model": old.get("summary_model", "sonnet"),
        "sweep_model": old.get("sweep_model", "haiku"),
    })
    claude = shutil.which("claude")
    if claude:
        cfg["claude_path"] = util.fwd(claude)

    write_runtime(python)
    vault_created = build_vault(cfg, {"name": a.name, "about": a.about})
    record.setdefault("vault_created", vault_created)

    settings = read_settings()
    record.setdefault("settings_created", settings is None)
    if "settings_had_hooks" not in record:
        record["settings_had_hooks"] = bool(settings) and "hooks" in settings
    backups = record.setdefault("settings_backups", [])
    write_settings(merge_settings(settings or {}), backups)

    md = install_claude_md(cfg)
    if md is not None:
        record["claude_md"] = md
    cfg["installed"] = record
    util.save_config(cfg)

    notes = []
    if "backup" in mods:
        e = setup_git(vault_path)
        if e:
            notes.append(e)
    if ("summary" in mods or "sweep" in mods) and not claude:
        notes.append("`claude` CLI not found on PATH; summary/sweep need it")
    try:
        from . import search
        search.update_index(vault_path, cfg).close()
    except Exception as e:  # doctor will report it
        notes.append(f"search index: {e}")

    util.out(f"jarvan-memory {__version__} installed.")
    util.out(f"  vault:   {cfg['vault']}{' (created)' if vault_created else ' (existing, kept)'}")
    util.out(f"  python:  {python}")
    util.out(f"  command: {cfg['mem_cmd']}")
    util.out(f"  modules: {', '.join(mods) or 'none'}")
    for n in notes:
        util.out(f"  note: {n}")
    if a.no_doctor:
        return 0
    from . import doctor
    util.out("")
    return doctor.main()


# ----------------------------------------------------------------- uninstall

def uninstall(purge_vault=False, yes=False):
    cfg = util.load_config()
    record = cfg.get("installed", {})
    if purge_vault and not yes:
        util.err("--purge-vault deletes every note. Ask the user, then pass --yes as well.")
        return 1
    p = settings_path()
    backups = [Path(b) for b in record.get("settings_backups", [])]
    if p.exists():
        data = read_settings() or {}
        data = strip_ours(data)
        if not record.get("settings_had_hooks") and data.get("hooks") == {}:
            del data["hooks"]
        first = backups[0] if backups and backups[0].exists() else None
        if record.get("settings_created") and not data:
            p.unlink()
        elif first and _json_equal(first, data):
            # Nothing else changed since install: put the original bytes back.
            shutil.copy2(first, p)
        else:
            util.write_text(p, json.dumps(data, indent=2, ensure_ascii=False) + "\n")
    for b in backups:
        b.unlink(missing_ok=True)
    remove_claude_md(record.get("claude_md"))
    vroot = Path(cfg["vault"])
    app = util.app_dir()
    shutil.rmtree(app, ignore_errors=True)
    if app.exists():
        # Windows keeps a running mem.cmd open; say so instead of leaving it silently.
        util.err(f"Could not remove everything in {app} (a file is in use). Delete that "
                 "folder by hand; nothing in it is needed any more.")
    if purge_vault:
        shutil.rmtree(vroot, ignore_errors=True)
        util.out(f"Removed jarvan-memory and the vault {vroot}.")
    else:
        util.out(f"Removed jarvan-memory. The vault is kept at {vroot}.")
    return 0


def _json_equal(path, data):
    try:
        return json.loads(Path(path).read_text(encoding="utf-8-sig")) == data
    except (OSError, ValueError):
        return False


def repair_python(explicit=None):
    cfg = util.load_config()
    python = find_python(explicit)
    if not python:
        util.err("No working Python 3.9+ found. Install one (see INSTALL.md) and retry, or "
                 "pass --python <absolute path>.")
        return 1
    # Regenerate only the shims; the runtime copy is already in place.
    write_shims(python)
    cfg["python"] = python
    util.save_config(cfg)
    util.out(f"hooks now use {python}")
    return 0
